data = json.load(open("yijing.json", encoding="utf-8"))

# 校验：由上下卦推导的二进制必须与爻辞中的「初九/初六」等一致
errors = []
for h in data:
    lower = ALIAS[h["lower"]]
    upper = ALIAS[h["upper"]]
    lines = TRIGRAM_BITS[lower] + TRIGRAM_BITS[upper]
    h["lower"] = lower
    h["upper"] = upper
    h["lines"] = lines

    for idx, yao in enumerate(h["yaoci"]):
        if yao.startswith("用九") or yao.startswith("用六"):
            continue
        m = re.match(r"^(初|上|[九六])([九六])?([一二三四五])?", yao)
        label = yao.split("：")[0]
        pos = None
        if label.startswith("初"):
            pos = 1
        elif label.startswith("上"):
            pos = 6
        else:
            mm = re.match(r"^[九六]([一二三四五])", label)
            if mm:
                pos = {"一": 2, "二": 2, "三": 3, "四": 4, "五": 5}[mm.group(1)]
                # 九二→2, 九三→3 ... 九五→5
                pos = {"一": 2, "二": 2, "三": 3, "四": 4, "五": 5}[mm.group(1)]
        if pos is None:
            continue
        expect = 1 if "九" in label[:2] else 0
        if lines[pos - 1] != expect:
            errors.append((h["no"], h["name"], pos, label, lines))

print("卦象自校验错误:", len(errors))
for e in errors[:10]:
    print("  ", e)

